console.log("wrong key text:", (await p.textContent("#unlockMsg")).replace(/\s+/g, " ").slice(0, 160));
await p.screenshot({ path: "/tmp/glitchlock-ui.png", fullPage: true });
console.log("errors:", errs.length ? errs : "none");
console.log("RESULT", /Byte-exact/.test(verdict) ? "PASS" : "FAIL");
await b.close();
